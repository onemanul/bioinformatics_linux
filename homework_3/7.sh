#!/bin/bash

i=$1

if [[ $# -ne 1 ]]; then
  echo "Неверное количество аргументов, должен быть 1"
  exit 1
fi

if [[ ! "$i" =~ ^[0-9]+$ ]]; then
  echo "Аргумент должен быть целым положительным числом"
  exit 1
fi

while [ $i -gt 0 ];do
  echo "$(printf "%${i}s" | tr ' ' '*')" # создаст строку с i пробелами - заменит их на *
  ((--i))
  sleep 1
done
echo "Время вышло"
